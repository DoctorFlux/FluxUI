"""TOC/XML-aware static inventory; registration sites are candidates, not CPU measurements."""
from collections import Counter
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CLIENTS = {"Retail": "mainline", "Forever": "camelot", "Era": "vanilla", "Anniversary": "tbc"}


def read(path):
    return path.read_bytes().decode("utf-8-sig", errors="replace")


def loaded_files():
    found = {}
    missing = set()

    def visit(path, clients):
        path = path.resolve()
        if not path.is_file():
            missing.add(str(path.relative_to(ROOT)))
            return
        fresh = set(clients) - found.get(path, set())
        if not fresh:
            return
        found.setdefault(path, set()).update(fresh)
        if path.suffix.lower() == ".xml":
            text = re.sub(r"<!--[\s\S]*?-->", "", read(path))
            for item in re.findall(r'<(?:Script|Include)\b[^>]*\bfile=["\']([^"\']+)', text, re.I):
                visit(path.parent / item.replace("\\", "/"), fresh)

    for line in read(ROOT / "_FluxUI.toc").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        gate = re.search(r"\[AllowLoadGameType ([^]]+)\]", line)
        clients = set(CLIENTS)
        if gate:
            allowed = {v.strip() for v in gate[1].split(",")}
            clients = {c for c, game in CLIENTS.items() if game in allowed}
        if clients:
            visit(ROOT / line.split(" [")[0].replace("\\", "/"), clients)
    return found, missing


PATTERNS = {
    "OnUpdate": r'(?:SetScript|HookScript)\s*\(\s*["\']OnUpdate["\']\s*,(?!\s*nil\b)\s*',
    "Ticker": r'\b(?:NewTicker|ScheduleRepeatingTimer|Ticker\.Add)\s*\(',
    "Timer": r'\b(?:After|NewTimer)\s*\(',
    "Event": r'\b(?:RegisterEvent|RegisterUnitEvent|Ev\.Register|Events\.Register|SafeRegisterEvent|FluxSafeRegisterEvent)\s*\(',
    "Hook": r'\b(?:hooksecurefunc|HookScript)\s*\(',
}


def inventory():
    files, missing = loaded_files()
    out = ["# Loaded performance entry points", "",
           "Generated by `python tests/performance_inventory.py`. Static registration sites, not measured hotspots.",
           "TOC client gates and XML includes are followed; runtime feature gates still apply.",
           "Legacy unloaded implementations and backup files are excluded. Dynamic registration and native animation costs need in-game capture.", "",
           f"Reachable files: {len(files)}. Missing references: {len(missing)}.", "",
           "| File | TOC clients | OnUpdate | Ticker | Timer | Event | Hook |",
           "|---|---|---:|---:|---:|---:|---:|"]
    drivers = []
    totals = Counter()
    for path in sorted(files):
        if path.suffix.lower() not in (".lua", ".xml"):
            continue
        counts = Counter()
        for number, line in enumerate(read(path).splitlines(), 1):
            if line.lstrip().startswith(("--", "<!--")):
                continue
            for kind, pattern in PATTERNS.items():
                if re.search(pattern, line):
                    counts[kind] += 1
                    if kind in ("OnUpdate", "Ticker"):
                        drivers.append((path.relative_to(ROOT).as_posix(), number, kind, line.strip()))
        if counts:
            relative = path.relative_to(ROOT).as_posix()
            cells = [f"`{relative}`", ", ".join(c for c in CLIENTS if c in files[path])]
            cells += [str(counts[k]) for k in PATTERNS]
            out.append("| " + " | ".join(cells) + " |")
            totals.update(counts)
    out += ["", "Static totals: " + ", ".join(f"{k}={totals[k]}" for k in PATTERNS), "",
            "## Recurring-driver registration sites", "",
            "A listed driver may run only during a cast, drag, hover, or bounded initialization. Names and registrations alone do not prove idle CPU cost.", ""]
    for path, number, kind, line in drivers:
        out.append(f"- `{path}:{number}` ({kind}): `{line.replace('`', '')}`")
    if missing:
        out += ["", "## Missing references", ""] + [f"- `{p}`" for p in sorted(missing)]
    (ROOT / "docs/performance-driver-inventory.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(files)} reachable files, {len(missing)} missing; {dict(totals)}; {len(drivers)} recurring sites")
    return files


if __name__ == "__main__":
    inventory()
