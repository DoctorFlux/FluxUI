"""Regenerate source-derived documentation inventories; writes only under docs/.

Run from any directory: python docs/tools/build_reference.py
The separate validate_docs.py command never regenerates or edits documentation.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path
from urllib.parse import quote

sys.dont_write_bytecode = True
from source_inventory import ROOT, collect, literal

DOCS = ROOT / "docs"


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ").replace("\r", "").replace("<", "&lt;").replace(">", "&gt;")


def code(value):
    return "`" + cell(value).replace("`", "'") + "`"


def short(value, length=180):
    value = re.sub(r"\s+", " ", value).strip()
    return value if len(value) <= length else value[:length - 1] + "…"


def link(path, line=None, depth=1, label=None):
    target = "../" * depth + quote(path, safe="/._-")
    if line:
        target += "#L" + str(line)
    return "[" + cell(label or (path + (":" + str(line) if line else ""))) + "](" + target + ")"


def write(name, lines):
    path = DOCS / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")


def source_coverage(data):
    files = data["files"]
    counts = Counter(f["classification"] for f in files)
    lines = ["# Source coverage and executable scope", "", "Generated by `python docs/tools/build_reference.py`; validated without writes by `python docs/tools/validate_docs.py`.", "",
             "This index maps every addon-owned Lua/XML source and local smoke harness to a chapter, and inventories bundled library files. A chapter mapping is an ownership index; use its prose and source links for behavioral explanations. Presence in this table does not mean the file executes.", "",
             "The TOC/XML closure contains **" + str(len(data["graph"]["reachable"])) + " files**. `Bindings.xml` is additionally classified as active binding data through the TOC metadata/WoW binding loader. TOC gates are listed using their literal identifiers; runtime client/capability/dependency guards can further restrict a file. See [client detection](02-multi-client-matrix.md).", "",
             "Files excluded: Git metadata, local editor settings, backup directories, ignored development/extraction caches, generated Python caches, documentation code, and non-Lua/XML assets (covered in [assets](34-assets.md)). Unloaded source is described as inactive rather than assumed obsolete or safe to delete.", "",
             "Source SHA-256 fingerprints normalize CRLF to LF and preserve every other byte, including any BOM. This makes the same Git source verifiable on Windows and LF checkouts without rewriting addon files. Resource asset hashes are raw-byte hashes. Inventory format 2 records this policy explicitly.", "",
             "## Classification totals", "", "| Classification | Files |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(counts.items())]
    lines += ["", "## Addon sources", "", "| Source | Classification | TOC clients | Chapter |", "|---|---|---|---|"]
    for f in files:
        if f["path"].startswith("libs/"):
            continue
        lines.append("| " + link(f["path"]) + " | " + f["classification"] + " | " + cell(", ".join(f["clients"]) or "—") + " | [" + f["chapter"] + "](" + f["chapter"] + ") |")
    lines += ["", "## Bundled library packages", "", "Libraries are documented at package level in [dependencies and provenance](90-reference-inspirations.md). Individual load paths and hashes remain in [inventory.json](reference/inventory.json).", "", "| Package | Sources on disk | Reachable files |", "|---|---:|---:|"]
    packages = defaultdict(list)
    for f in files:
        if f["path"].startswith("libs/"):
            packages[f["path"].split("/")[1]].append(f)
    for name, group in sorted(packages.items()):
        lines.append(f"| {cell(name)} | {len(group)} | {sum(bool(f['clients']) for f in group)} |")
    lines += ["", "## Load order and late dependencies", "", "The following is the union traversal order, with client filters retained in the inventory. XML children follow their inclusion point. Event-driven initialization may execute later; this is not a wall-clock initialization trace.", "", "| Position | Source | Included by |", "|---:|---|---|"]
    for i, rel in enumerate(data["graph"]["order"], 1):
        if rel.startswith("libs/"):
            continue
        lines.append(f"| {i} | {link(rel)} | {cell(', '.join(data['graph']['reachable'][rel]['parents']))} |")
    lines += ["", "### Explicit dependency load sites", "", "These load external addon packages; their contents are not bundled FluxUI source. Calls may be conditional, protected with pcall, or fallbacks for one another.", "", "| Caller | Load expression |", "|---|---|"]
    for f in files:
        if f["clients"]:
            for item in f["loads"]:
                lines.append(f"| {link(f['path'], item['line'])} | {code(item['method'] + '(' + ', '.join(item['arguments']) + ')')} |")
    write("30-source-coverage.md", lines)


def settings(data):
    lines = ["# Setting definitions and custom control sites", "", "Generated from Lua table constructors and factory call sites. This is the exhaustive source-definition companion to the [options map](../26-options-map.md), not an evaluated screenshot of a particular character's options.", "",
             "A definition can be a group, header, description, actionable setting, or custom embedded control. Factory templates and their calls are listed separately: one runtime control per skill/unit/row can originate at a single source site. Full expressions, getter/setter bodies, and line locations are retained in [inventory.json](inventory.json). Expressions are source evidence, not values evaluated by this tool.", "",
             "Shared literal defaults are in [defaults](defaults.md); feature-owned fallbacks are in the getter excerpts and linked feature chapters. A default table is not proof of the effective value after migrations, CVars, character overrides, or user configuration.", ""]
    interesting = ("desc", "values", "min", "max", "step", "get", "set", "func", "hidden", "disabled", "dialogControl", "confirm", "confirmText")
    for f in data["files"]:
        if not f["settings"] and not f.get("setting_factories"):
            continue
        lines += ["## " + f["path"].split("/")[-1], "", link(f["path"], depth=2), ""]
        for s in f["settings"]:
            fields = s["fields"]
            name = literal(fields.get("name", ""))
            label = short(name if name is not None else fields.get("name", s["key"]), 110)
            label = label.strip() or s["key"]
            lines += ["### " + cell(s["key"]) + " · " + cell(label) + " · L" + str(s["line"]), "", "Source: " + link(f["path"], s["line"], 2) + ". Type: " + code(fields.get("type", "custom toggle descriptor")) + ".", ""]
            if "desc" in fields:
                desc = literal(fields["desc"])
                if desc is not None:
                    lines += [cell(desc), ""]
            lines += ["| Contract | Source expression / implementation |", "|---|---|"]
            for key in interesting:
                if key not in fields or key == "desc":
                    continue
                value = fields[key]
                line = s["field_lines"][key]
                lines.append("| " + key + " | " + code(short(value, 250)) + " " + link(f["path"], line, 2, "source") + " |")
            lines.append("")
        if f.get("setting_factories"):
            lines += ["### Factory expansions", "", "Arguments select storage keys, unit names, labels, fallback values, ordering, and conditional availability. Follow the corresponding factory definition for the resulting getter/setter contract.", "", "| Site | Factory and arguments |", "|---|---|"]
            for call in f["setting_factories"]:
                lines.append("| " + link(f["path"], call["line"], 2) + " | " + code(short(call["method"] + "(" + ", ".join(call["arguments"]) + ")", 600)) + " |")
            lines.append("")
    lines += ["## Registered custom widgets", "", "Registration expressions can use local `Type` constants. Exact widget names, interaction behavior, and storage are explained in the options map; this table keeps every registration site discoverable.", "", "| Source | Registration arguments |", "|---|---|"]
    for f in data["files"]:
        if f["clients"]:
            for w in f["widgets"]:
                lines.append("| " + link(f["path"], w["line"], 2) + " | " + code(short(", ".join(w["arguments"]), 200)) + " |")
    write("reference/settings-details.md", lines)
    lines = ["# Literal AceDB defaults", "", "Generated from [FluxOptionsDefaults.lua](../../AddonOptions/FluxOptionsDefaults.lua). These are declared defaults, not a dump of a user's settings. Independent scopes and feature-owned fallbacks are explained in [persistence](../09-persistence.md) and [options](../26-options-map.md). Empty containers are represented by the owning schemas and source file.", "", "| Path | Literal default | Source |", "|---|---|---|"]
    for d in data["defaults"]:
        lines.append("| " + code(d["path"]) + " | " + code(d["value"]) + " | " + link("AddonOptions/FluxOptionsDefaults.lua", d["line"], 2, "definition") + " |")
    write("reference/defaults.md", lines)


def declarations(data):
    lines = ["# Command and SavedVariable declaration evidence", "", "Generated companion to [commands](../31-commands-and-bindings.md) and [saved data](../32-saved-variables.md). Only reachable production files are included below. A registration site can still have runtime guards; execution and callback ordering must be traced in the implementation.", "", "## Slash registrations in union load order", "", "| Source | Kind | Command key / registration | Value |", "|---|---|---|---|"]
    by_path = {f["path"]: f for f in data["files"]}
    for rel in data["graph"]["order"]:
        f = by_path[rel]
        for s in f["slash"]:
            lines.append("| " + link(rel, s["line"], 2) + " | " + s["kind"] + " | " + code(s["name"]) + " | " + code(s.get("value", ", ".join(s.get("arguments", [])))) + " |")
    lines += ["", "## SavedVariable reference sites", "", "References include exact identifier and string-key tokens. Counts do not prove writes or active ownership. Core/DB table initialization and retained migration references must be distinguished from actual feature consumers.", "", "| SavedVariable | Declared scope | Active reference files | Inactive reference files |", "|---|---|---|---|"]
    for sv in data["graph"]["saved_variables"]:
        active, inactive = [], []
        for f in data["files"]:
            for site in f["sv_sites"]:
                if site["name"] == sv["name"]:
                    (active if f["clients"] else inactive).append(link(f["path"], site["lines"][0], 2))
        lines.append("| " + code(sv["name"]) + " | " + sv["scope"] + " | " + "<br>".join(active or ["No exact token sites"]) + " | " + "<br>".join(inactive or ["—"]) + " |")
    write("reference/declarations.md", lines)


def interfaces(data):
    lines = ["# Source interface and event index", "", "Generated discovery index for [API/event contracts](../33-api-and-events.md). Function declarations are syntactic candidates: table-local methods are included, and assigned aliases/dynamically generated functions may not appear. This is not a promise that every name is globally accessible. Stable contracts and callback payloads are documented in the architecture/system chapters.", "", "## Event and subscription sites", "", "Literal and dynamic event expressions are preserved. Shared-bus subscription methods can subscribe to non-WoW notifications; method names alone do not establish event semantics.", "", "| Source | Method | Arguments |", "|---|---|---|"]
    for f in data["files"]:
        if f["clients"]:
            for e in f["events"]:
                lines.append("| " + link(f["path"], e["line"], 2) + " | " + code(e["method"]) + " | " + code(short(", ".join(e["arguments"]), 260)) + " |")
    lines += ["", "## Declared interface candidates", "", "Each source heading links back to its owning chapter. Use search for a particular method; use the chapter to understand its lifecycle and data invariants.", ""]
    for f in data["files"]:
        if not f["clients"] or not f["functions"]:
            continue
        lines += ["### " + f["path"], "", "Owner: [" + f["chapter"] + "](../" + f["chapter"] + ").", "", "| Declaration | Source |", "|---|---|"]
        for fun in f["functions"]:
            lines.append("| " + code(fun["name"]) + " | " + link(f["path"], fun["line"], 2, "L" + str(fun["line"])) + " |")
        lines.append("")
    write("reference/interfaces.md", lines)


def performance(data):
    lines = ["# Current recurring-driver source inventory", "", "Generated from the current TOC/XML closure by `python docs/tools/build_reference.py`. Replaces the stale September generator output; the [September audit](performance-audit-2026-09-19.md) remains historical evidence.", "", "Counts below are lexical call/assignment candidates after removing comments and string contents. They are not measured hotspots, simultaneously active drivers, frame counts, or proof of idleness. Native animations, indirect calls and wrappers need runtime capture. Shared-service subscriptions are included because clients can run from a shared driver.", "", "| Source | OnUpdate references | Ticker calls | Timer calls | Event/subscription sites | Hook calls |", "|---|---:|---:|---:|---:|---:|"]
    from source_inventory import tokens
    for f in data["files"]:
        if not f["clients"] or f["path"].startswith("libs/") or not f["path"].endswith(".lua"):
            continue
        ts = tokens((ROOT / f["path"]).read_text(encoding="utf-8-sig", errors="replace"))
        onupdate = sum(t.kind == "string" and literal(t.value) == "OnUpdate" for t in ts)
        tick = sum(t.value in ("NewTicker", "Ticker") and i + 1 < len(ts) and ts[i + 1].value == "(" for i, t in enumerate(ts))
        timers = sum(t.value in ("After", "NewTimer") and i + 1 < len(ts) and ts[i + 1].value == "(" for i, t in enumerate(ts))
        hooks = sum(t.value in ("hooksecurefunc", "HookScript") and i + 1 < len(ts) and ts[i + 1].value == "(" for i, t in enumerate(ts))
        if any((onupdate, tick, timers, len(f["events"]), hooks)):
            lines.append(f"| {link(f['path'])} | {onupdate} | {tick} | {timers} | {len(f['events'])} | {hooks} |")
    lines += ["", "For capture commands and interpretation, read [verification](41-verification.md) and [shared diagnostics](08-shared-services.md)."]
    write("performance-driver-inventory.md", lines)


def main():
    data = collect()
    data["clients"] = list(data["clients"])
    if data["graph"]["missing"]:
        raise SystemExit("Missing/invalid load references: " + repr(data["graph"]["missing"]))
    destination = DOCS / "reference/inventory.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    source_coverage(data)
    settings(data)
    declarations(data)
    interfaces(data)
    performance(data)
    print(f"Generated documentation inventory: {len(data['files'])} sources; {len(data['graph']['reachable'])} TOC/XML reachable; {sum(len(f['settings']) for f in data['files'])} setting definitions; {len(data['defaults'])} literal defaults.")


if __name__ == "__main__":
    main()
